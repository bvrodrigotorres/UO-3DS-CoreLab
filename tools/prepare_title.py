"""Prepare the generated title painting for a 400x240 RGB565 software HUD.
Requires Pillow; outputs are committed so builds need no image dependencies.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
# UI lettering remains crisp at the console's actual resolution. Version and
# loading status are drawn by hud.cpp, never baked into the illustration.
im=Image.open(ROOT/'art/title-source-v042.png').convert('RGB').resize((1600,960),Image.Resampling.LANCZOS)
d=ImageDraw.Draw(im)
font=ImageFont.truetype('/System/Library/Fonts/Supplemental/Baskerville.ttc',144,index=1)
small=ImageFont.truetype('/System/Library/Fonts/Supplemental/Baskerville.ttc',92,index=1)
for word,y,f in [('Ultima Online',200,font),('3DS',365,small)]:
    b=d.textbbox((0,0),word,font=f);x=(1600-(b[2]-b[0]))/2-b[0]
    d.text((x+5,y+7),word,font=f,fill=(8,9,16),stroke_width=7,stroke_fill=(8,9,16))
    d.text((x,y),word,font=f,fill=(238,205,128),stroke_width=1,stroke_fill=(171,120,49))
im=im.resize((400,240),Image.Resampling.LANCZOS)
im.save(ROOT/'art/title-v042.png')
values=[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b in im.getdata()]
lines=['// Generated by tools/prepare_title.py. Do not edit.','#pragma once','#include <cstdint>','namespace lab {','inline constexpr uint16_t TitleArt[400*240]={']
lines.extend(','.join(f'0x{v:04x}' for v in values[i:i+16])+',' for i in range(0,len(values),16))
lines+=['};','}']
(ROOT/'include/title_art.hpp').write_text('\n'.join(lines)+'\n')
