inline size_t labelPixelOffset(unsigned x,unsigned y){
    // PICA 8x8 Morton tiles; logical image origin is top left.
    unsigned morton=0;
    for(unsigned bit=0;bit<3;++bit){morton|=((x>>bit)&1)<<(2*bit);morton|=((y>>bit)&1)<<(2*bit+1);}
    return ((y/8)*16+x/8)*64+morton;
}
inline bool labelPixel(unsigned c,unsigned x,unsigned y){return c<128&&x<5&&y<7&&(LabelGlyphs[c][y]&(1<<(4-x)));}
